-- =============================================================================
-- Clearing an instalment cell: a correction, not a cancellation.
-- =============================================================================
--
-- NOT APPLIED TO LIVE. For Dom's review, because it reinstates something
-- he told me to take out on 12 November and the reason is new.
--
-- WHAT HE SAID, AND WHY THIS COMES BACK
--   Reviewing the ledger migration he wrote: "Rule 7 — add the cancelled
--   marker and remove the client delete path (or explain why delete is
--   safe)." I added the marker and removed the delete. Building the sales
--   grid on top of it turned up the case neither of us had in front of us:
--   **clearing a cell of the schedule now does nothing at all**, silently.
--   RLS refuses the delete, which is a success with no error and no rows,
--   and the form says "Sale updated."
--
--   So there are two different things that look the same on screen, and
--   the ledger needs both:
--
--     · **A cancellation.** The customer stopped paying. That is a fact
--       about them and about the business, it has a month, and the report
--       should be able to say so. `cancelled_on`, which rule 7 is for, and
--       which this does not touch.
--
--     · **A correction.** Somebody typed £500 into December and meant
--       November. There is no counterparty, no agreement and no fact —
--       the row records an intention that never existed. Nothing is
--       preserved by keeping it, and keeping it puts money in the grid
--       that nobody is ever going to send.
--
--   That second case is the one `report_top_items` already answers the
--   same way: a mistyped top-three line is deleted, because a line nobody
--   meant is not a record of anything. Marking it instead would leave
--   "cancelled" against an instalment nobody ever agreed to, which says
--   something untrue about the customer.
--
-- WHAT STOPS IT BEING A HOLE
--   `guard_report_sale_payment_months` already fences DELETE, and it was
--   written before this policy existed:
--
--     · A delete on a published DUE month is refused.
--     · A delete of money RECEIVED in a published month is refused.
--     · Admin and the service role pass, as everywhere.
--
--   So a correction is possible exactly while the month is the team's
--   working-out, and the moment a client has read it the only way money
--   leaves the ledger is `cancelled_on`. That is the line rule 7 draws,
--   and it is drawn by the guard rather than by the absence of a policy.
--
--   The action checks what came back, too: `saveSale` deletes with a
--   `returning` and reports a cell it could not clear, rather than saying
--   "saved" to a write the database refused.
create policy report_sale_payments_delete_editors on public.report_sale_payments
  for delete to authenticated using (public.report_can_edit(workspace_id));

comment on table public.report_sale_payments is
  'One instalment: the month it is due, and the month the money actually arrived. Cash counts on received_month. A cell can be cleared while the month is a draft, because an instalment nobody meant is not a record of anything; once a month is published, money leaves the ledger by being cancelled (12 Nov 2026).';
